"""Assembly-module generator for the block sieve (the Asm modules; see FORMAT.md, section 5).

    python3 gen_asm.py <out-dir> <xs.json> <block-dir> [<block-dir> ...] [--sigma 100000] [--params F X N W.txt]
    python3 gen_asm.py --verify <dir> <xs.json> <block-dir> [...] [--sigma 100000] [--params F X N W.txt]

Inputs (all pinned): xs.json = {"xs": [[m, Y], ...]} from make_xs.py (the scan's exception lanes, each with the Y at
which `checkAt` settles it, or 0 for a W18 field; Y is DATA that asmB checks); the block dirs written by gen_blocks.py
(each Gen/<fam>/B*.lean; the block constant is read from its `def NAME : Blk` line).

Writes, under <out-dir>/BoundariesOfClass/Sieve/Block/Asm/:
- SP/Chunk_kkk.lean: (p, sqMask p) for 2 and the odd primes <= YP = max listed Y, Σp <= sigma per chunk, and ONE
  theorem `spChunkB chunk_kkk = true := by decide +kernel` (maxRecDepth line above it);
- SP/P.lean: `P := (<balanced ++ tree of chunk groups>).flatten`, ONE decided `incr (P.map (·.1)) = true`, the
  generated `P_chunks_ok` (forall_mem_append / forall_mem_cons, never decide) and `P_ok : PrimesOK P`;
- Main.lean: imports every block and SP.P; `Bs := <balanced ++ tree of block groups>`, `xs`, ONE decided
  `asmB Bs SP.P xs = true`, the generated `hB` (each block `⟨Base.pats_ok, blk_ok, rfl⟩`, never decide) and
  `asm_cx : Covers Bs 227932027 1605000000 ∧ ExceptionsOK Bs`;
- MANIFEST_asm.json (md5 of every file).

Nesting is a balanced binary tree of `++` over groups of at most GROUP items (depth about log2(n/GROUP) + GROUP), since
the elaborator's default maxRecDepth breaks a 227-deep nested term (measured) and a manifest file may raise it only on
its decide theorem.

Without --params, Main decides the h <= 1000 instance `asmB` of lean/.../Block/AsmCheck.lean (F = 227932027,
X = 1605000000, N = 1000, the W18 list) and derives `Covers` and `ExceptionsOK` from it by the proved
`covers_exceptionsOK_of_asmB`.

--params F X N W.txt: Main instead gets a local `asmP`, which is asmB's body with the three residue chains over
[F + 1, X) and [F/4 + 1, (X + 3)/4), the W list read from W.txt (one radicand per line) and `checkAt N`. The decided
theorem is then `asmP Bs SP.P xs = true`. Its soundness lemma is the parametrised form of
`covers_exceptionsOK_of_asmB` (DESIGN.md, section 6: a mechanical generalisation, NOT yet built), so such a Main is
the shape the h <= 3500 instance will take, and the example uses it.
"""
import hashlib, json, math, re, sys
from pathlib import Path

ROOT = "BoundariesOfClass.Sieve.Block"
REL = Path("BoundariesOfClass/Sieve/Block/Asm")
GROUP = 16

def primes_upto(n):
    s = bytearray([1]) * (n + 1); s[0:2] = b"\0\0"
    for p in range(2, math.isqrt(n) + 1):
        if s[p]: s[p * p::p] = bytearray(len(s[p * p::p]))
    return [i for i in range(n + 1) if s[i]]

def sq_mask(p):
    m = 0
    for y in range(p): m |= 1 << (y * y % p)
    return m

def chunks_of(ps, sigma):
    out, cur, tot = [], [], 0
    for p in ps:
        if cur and tot + p > sigma: out.append(cur); cur, tot = [], 0
        cur.append(p); tot += p
    if cur: out.append(cur)
    return out

def tree(items, leaf, join):
    """Balanced binary tree over groups of at most GROUP items."""
    groups = [items[i:i + GROUP] for i in range(0, len(items), GROUP)] or [[]]
    def go(gs):
        if len(gs) == 1: return leaf(gs[0])
        h = len(gs) // 2
        return join(go(gs[:h]), go(gs[h:]))
    return go(groups)

def list_tree(names):
    return tree(names, lambda g: "[" + ", ".join(g) + "]", lambda a, b: f"({a} ++\n    {b})")

def mem_tree(proofs):
    def leaf(g):
        t = "List.forall_mem_nil _"
        for pr in reversed(g): t = f"List.forall_mem_cons.2 ⟨{pr}, {t}⟩"
        return t
    return tree(proofs, leaf, lambda a, b: f"List.forall_mem_append.2 ⟨{a},\n    {b}⟩")

def read_blocks(dirs):
    out = []
    for d in dirs:
        for p in sorted(Path(d).glob("Gen/*/B*.lean")):
            m = re.search(r"^def (\S+) : Blk", p.read_text(), re.M)
            fam = p.parent.name
            out.append((f"{ROOT}.Gen.{fam}.{p.stem}", f"{ROOT}.Gen.{m.group(1)}"))
    return out

def render(xs, blocks, sigma, test):
    files = {}
    ys = [y for _, y in xs if y > 0]
    yp = max(ys) if ys else 2
    ps = primes_upto(yp)
    ch = chunks_of(ps, sigma)
    w = max(3, len(str(len(ch) - 1)))
    names = [f"chunk_{k:0{w}d}" for k in range(len(ch))]
    for name, qs in zip(names, ch):
        lit = ",\n  ".join(f"({p}, {sq_mask(p)})" for p in qs)
        files[REL / "SP" / f"Chunk_{name[6:]}.lean"] = (
            f"import {ROOT}.AsmCheck\n\n"
            f"/-! Generated by gen_asm.py: sieve primes {qs[0]}..{qs[-1]}, sum {sum(qs)}. -/\n\n"
            f"namespace {ROOT}.Asm.SP\n\n"
            f"def {name} : List (ℕ × ℕ) := [\n  {lit}]\n\n"
            f"set_option maxRecDepth 1000000 in\n"
            f"theorem {name}_ok : spChunkB {name} = true := by decide +kernel\n\n"
            f"end {ROOT}.Asm.SP\n")
    imps = "".join(f"import {ROOT}.Asm.SP.Chunk_{n[6:]}\n" for n in names)
    lt = list_tree(names)
    files[REL / "SP" / "P.lean"] = (
        f"import {ROOT}.AsmCheck\n{imps}\n"
        f"/-! Generated by gen_asm.py: the sieve primes of checkAt, {len(ps)} primes 2..{ps[-1]} in "
        f"{len(ch)} chunks. -/\n\n"
        f"namespace {ROOT}.Asm.SP\n\n"
        f"def P : List (ℕ × ℕ) := ({lt}).flatten\n\n"
        f"set_option maxRecDepth 1000000 in\n"
        f"theorem P_incr : incr (P.map (·.1)) = true := by decide +kernel\n\n"
        f"theorem P_chunks_ok : ∀ l ∈ ({lt}), spChunkB l = true :=\n  {mem_tree([n + '_ok' for n in names])}\n\n"
        f"theorem P_ok : PrimesOK P := primesOK_of_spChunks P_chunks_ok P_incr\n\n"
        f"end {ROOT}.Asm.SP\n")
    bimps = "".join(f"import {m}\n" for m, _ in blocks)
    bs = list_tree([c for _, c in blocks])
    xs_lit = "[" + ", ".join(f"({m}, {y})" for m, y in xs) + "]"
    hb = mem_tree([f"⟨Base.pats_ok, {c}_ok, rfl⟩" for _, c in blocks])
    if test:
        F, X, N, W = test
        wl = "[" + ", ".join(str(m) for m in W) + "]"
        decided = (f"/-- The parametrised assembly check (gen_asm --params): asmB's body with the three residue chains over\n"
                   f"[{F} + 1, {X}) and [{F} / 4 + 1, ({X} + 3) / 4), the W list {wl}, and checkAt {N}. -/\n"
                   f"def W : List ℕ := {wl}\n\n"
                   f"def asmP (Bs : List Blk) (P : List (ℕ × ℕ)) (xs : List (ℕ × ℕ)) : Bool :=\n"
                   f"  chainB 3 (up4 3 ({F} + 1)) {X} Bs && chainB 1 (up4 1 ({F} / 4 + 1)) (({X} + 3) / 4) Bs &&\n"
                   f"    chainB 2 (up4 2 ({F} / 4 + 1)) (({X} + 3) / 4) Bs &&\n"
                   f"    xs.all (fun mY => W.elem mY.1 || checkAt {N} mY.2 P mY.1) &&\n"
                   f"    Bs.all (fun b => Nat.beq b.E (maskFrom b xs))\n\n"
                   f"set_option maxRecDepth 1000000 in\n"
                   f"theorem asm_ok : asmP Bs SP.P xs = true := by decide +kernel\n\n")
        tail = ""
        hbN = N
    else:
        decided = (f"set_option maxRecDepth 1000000 in\n"
                   f"theorem asm_ok : asmB Bs SP.P xs = true := by decide +kernel\n\n")
        tail = (f"theorem asm_cx : Covers Bs 227932027 1605000000 ∧ ExceptionsOK Bs :=\n"
                f"  covers_exceptionsOK_of_asmB SP.P_ok asm_ok\n\n")
        hbN = 1000
    files[REL / "Main.lean"] = (
        f"import {ROOT}.AsmCheck\nimport {ROOT}.Asm.SP.P\n{bimps}\n"
        f"/-! Generated by gen_asm.py: {len(blocks)} blocks, {len(xs)} exception lanes. -/\n\n"
        f"namespace {ROOT}.Asm\n\n"
        f"def Bs : List Blk := {bs}\n\n"
        f"def xs : List (ℕ × ℕ) := {xs_lit}\n\n"
        f"{decided}"
        f"theorem asm_hB : ∀ b ∈ ({bs}), PatsOK b.pats ∧ blockOK b = true ∧ b.N = {hbN} :=\n  {hb}\n\n"
        f"{tail}"
        f"end {ROOT}.Asm\n")
    man = {str(k): hashlib.md5(v.encode()).hexdigest() for k, v in sorted(files.items(), key=lambda kv: str(kv[0]))}
    files[Path("MANIFEST_asm.json")] = json.dumps(man, indent=1, sort_keys=True) + "\n"
    return files, len(ch), len(ps), len(blocks)

def main(argv):
    sigma, test = 100000, None
    if "--sigma" in argv:
        i = argv.index("--sigma"); sigma = int(argv[i + 1]); del argv[i:i + 2]
    if "--params" in argv:
        i = argv.index("--params")
        W = sorted({int(l) for l in Path(argv[i + 4]).read_text().split()})
        test = (int(argv[i + 1]), int(argv[i + 2]), int(argv[i + 3]), W); del argv[i:i + 5]
    verify = argv and argv[0] == "--verify"
    if verify: argv = argv[1:]
    out, xs_p, bdirs = Path(argv[0]), Path(argv[1]), argv[2:]
    xs = [tuple(e) for e in json.loads(xs_p.read_text())["xs"]]
    files, nch, nps, nbl = render(xs, read_blocks(bdirs), sigma, test)
    if verify:
        bad = [str(r) for r, t in files.items() if not (out / r).exists() or (out / r).read_bytes() != t.encode()]
        extra = [str(p.relative_to(out)) for p in sorted((out / REL).rglob("*.lean"))] if (out / REL).exists() else []
        bad += [e + " (not generated)" for e in extra if Path(e) not in files]
        print("REGENERATE-AND-DIFF " + ("PASS" if not bad else "FAIL: " + ", ".join(bad[:10])))
        return 0 if not bad else 1
    for rel, text in files.items():
        p = out / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    print(f"{nbl} blocks, {len(xs)} exceptions, {nps} sieve primes in {nch} SP chunks" + (" (parametrised asmP)" if test else " (asmB, the h <= 1000 instance)"))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
