"""Shared-table generator for the block sieve (the Base modules; see FORMAT.md, section 3).

    python3 gen_shared.py <out-dir> <YMAX> <PMAX> [--sigma 100000]
    python3 gen_shared.py --verify <dir> <YMAX> <PMAX> [--sigma 100000]

The first form writes, under <out-dir>/BoundariesOfClass/Sieve/Block/Base/:
- Chunk_kkk.lean: a literal `chunk_kkk : List (ℕ × ℕ)` of (q, basePat q) for consecutive odd primes q ≤ YMAX, filled
  greedily so that Σq ≤ sigma (one prime alone may exceed it), plus ONE theorem
  `chunkOKB chunk_kkk = true := by decide +kernel` under `set_option maxRecDepth 1000000 in`;
- Pats.lean: `pats := ([chunk_000, …, chunk_015] ++ ([chunk_016, …] ++ …)).flatten` by definition (groups of 16), ONE decided theorem `incr (pats.map (·.1)) = true`,
  the generated `hc` term (nested `List.forall_mem_cons.2`, never decide) and `pats_ok : PatsOK pats`;
- Primes.lean: the literal `oddPrimes`, the odd primes ≤ PMAX (no theorem: blockOK decides `3 ≤ p ∧ p odd`, and
  NSQ needs nothing more);
- MANIFEST_shared.json (md5 of every file) and shared_lists.json (the two lists, for gen_blocks.py's mirror).

The second form regenerates into memory and compares byte for byte with <dir> (regenerate-and-diff; FORMAT.md, acceptance).
Output is deterministic: no timestamps, sorted keys. The patterns are DATA: each chunk theorem is what checks them.
"""
import hashlib, json, math, sys
from pathlib import Path

NS = "BoundariesOfClass.Sieve.Block.Base"
REL = Path("BoundariesOfClass/Sieve/Block/Base")

def primes_upto(n):
    s = bytearray([1]) * (n + 1); s[0:2] = b"\0\0"
    for p in range(2, math.isqrt(n) + 1):
        if s[p]: s[p * p::p] = bytearray(len(s[p * p::p]))
    return [i for i in range(n + 1) if s[i]]

def sq_mask(q):                 # Check.lean sqMask: bit (y*y % q) for every y < q
    m = 0
    for y in range(q): m |= 1 << (y * y % q)
    return m

def base_pat(q):                # BlockSieve basePat: bit n iff 4n % q != 0 and sqMask bit (q*q - 4n) % q
    sq = sq_mask(q)
    return sum(1 << n for n in range(q) if (4 * n) % q != 0 and (sq >> ((q * q - 4 * n) % q)) & 1)

def chunks_of(qs, sigma):
    out, cur, tot = [], [], 0
    for q in qs:
        if cur and tot + q > sigma:
            out.append(cur); cur, tot = [], 0
        cur.append(q); tot += q
    if cur: out.append(cur)
    return out

def render(ymax, pmax, sigma):
    pq = [q for q in primes_upto(ymax) if q > 2]
    ch = chunks_of(pq, sigma)
    w = len(str(len(ch) - 1)) if len(ch) > 1 else 1
    w = max(w, 3)
    names = [f"chunk_{k:0{w}d}" for k in range(len(ch))]
    mods = [f"Chunk_{k:0{w}d}" for k in range(len(ch))]
    files = {}
    for name, mod, qs in zip(names, mods, ch):
        lit = ",\n  ".join(f"({q}, {base_pat(q)})" for q in qs)
        files[REL / f"{mod}.lean"] = (
            f"import BoundariesOfClass.Sieve.Block.Defs\n\n"
            f"/-! Generated by gen_shared.py: {len(qs)} primes {qs[0]}..{qs[-1]}, sum {sum(qs)}. -/\n\n"
            f"namespace {NS}\n\n"
            f"def {name} : List (ℕ × ℕ) := [\n  {lit}]\n\n"
            f"set_option maxRecDepth 1000000 in\n"
            f"theorem {name}_ok : chunkOKB {name} = true := by decide +kernel\n\n"
            f"end {NS}\n")
    imports = "".join(f"import {NS}.{m}\n" for m in mods)
    # A 227-deep nested `forall_mem_cons` term exceeds the elaborator's default maxRecDepth (measured
    # 2026-10-25), and maxRecDepth may be raised only on a manifest file's decide theorem. So the chunk list is a
    # right-nested `++` of groups of at most HGROUP chunks, and hc is `forall_mem_append` over the groups with a short
    # `forall_mem_cons` chain in each: nesting depth about n/HGROUP + HGROUP instead of n.
    HGROUP = 16
    groups = [names[i:i + HGROUP] for i in range(0, len(names), HGROUP)]
    glits = ["[" + ", ".join(g) + "]" for g in groups]
    lst_expr = glits[-1]
    for gl in reversed(glits[:-1]):
        lst_expr = f"{gl} ++\n    ({lst_expr})"
    def chain(g):
        t = "List.forall_mem_nil _"
        for name in reversed(g):
            t = f"List.forall_mem_cons.2 ⟨{name}_ok, {t}⟩"
        return t
    hc = chain(groups[-1])
    for g in reversed(groups[:-1]):
        hc = f"List.forall_mem_append.2 ⟨{chain(g)},\n    {hc}⟩"
    lst = lst_expr
    files[REL / "Pats.lean"] = (
        f"import BoundariesOfClass.Sieve.Block.Lemmas\n{imports}\n"
        f"/-! Generated by gen_shared.py: the shared pattern table, {len(pq)} odd primes "
        f"3..{pq[-1]} in {len(ch)} chunks. -/\n\n"
        f"namespace {NS}\n\n"
        f"def pats : List (ℕ × ℕ) := ({lst}).flatten\n\n"
        f"set_option maxRecDepth 1000000 in\n"
        f"theorem pats_incr : incr (pats.map (·.1)) = true := by decide +kernel\n\n"
        f"theorem pats_chunks_ok : ∀ l ∈ ({lst}), chunkOKB l = true :=\n  {hc}\n\n"
        f"theorem pats_ok : PatsOK pats := patsOK_of_chunks pats_chunks_ok pats_incr\n\n"
        f"end {NS}\n")
    op = [p for p in primes_upto(pmax) if p > 2]
    # One list literal of ~4200 entries exceeds the elaborator's default maxRecDepth, and a manifest file may raise it
    # only on its decide theorem (gate v3.3 (j)); so the literal is split into groups of GROUP entries, joined by flatten.
    GROUP = 256
    grp = [op[i:i + GROUP] for i in range(0, len(op), GROUP)]
    gw = max(2, len(str(len(grp) - 1)))
    gnames = [f"oddPrimes_{k:0{gw}d}" for k in range(len(grp))]
    gdefs = "".join(f"def {n} : List ℕ := [{', '.join(map(str, g))}]\n\n" for n, g in zip(gnames, grp))
    files[REL / "Primes.lean"] = (
        f"import BoundariesOfClass.Sieve.Block.Defs\n\n"
        f"/-! Generated by gen_shared.py: the {len(op)} odd primes 3..{op[-1]} from which blocks select square primes, "
        f"in {len(grp)} groups of at most {GROUP}. -/\n\n"
        f"namespace {NS}\n\n"
        f"{gdefs}"
        f"def oddPrimes : List ℕ := [{', '.join(gnames)}].flatten\n\n"
        f"end {NS}\n")
    files[Path("shared_lists.json")] = json.dumps(
        {"YMAX": ymax, "PMAX": pmax, "sigma": sigma, "pats_primes": pq, "oddPrimes": op}, sort_keys=True) + "\n"
    man = {str(k): hashlib.md5(v.encode()).hexdigest() for k, v in sorted(files.items(), key=lambda kv: str(kv[0]))}
    files[Path("MANIFEST_shared.json")] = json.dumps(man, indent=1, sort_keys=True) + "\n"
    return files, len(ch), len(pq), len(op)

def main(argv):
    sigma = 100000
    if "--sigma" in argv:
        i = argv.index("--sigma"); sigma = int(argv[i + 1]); argv = argv[:i] + argv[i + 2:]
    verify = argv[0] == "--verify"
    if verify: argv = argv[1:]
    out, ymax, pmax = Path(argv[0]), int(argv[1]), int(argv[2])
    files, nch, npq, nop = render(ymax, pmax, sigma)
    if verify:
        bad = []
        for rel, text in files.items():
            p = out / rel
            if not p.exists() or p.read_bytes() != text.encode(): bad.append(str(rel))
        base = out / REL
        extra = sorted(str(p.relative_to(out)) for p in base.glob("*.lean")) if base.exists() else []
        extra = [e for e in extra if Path(e) not in files]
        for e in extra: bad.append(e + " (not generated)")
        print("REGENERATE-AND-DIFF " + ("PASS" if not bad else "FAIL: " + ", ".join(bad[:10])))
        return 0 if not bad else 1
    for rel, text in files.items():
        p = out / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    print(f"{nch} chunks, {npq} pattern primes (<= {ymax}), {nop} odd primes (<= {pmax}), sigma {sigma}")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
